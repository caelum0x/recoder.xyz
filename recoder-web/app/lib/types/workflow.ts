// Type guards for node types
export function isOperationNode(node: Node): node is OperationNode {
  return node.type === "operation";
}

export function isVariableNode(node: Node): node is VariableNode {
  return node.type === "variable";
}

export function isTextGenerationNode(node: Node): node is OperationNode & { content: TextGenerationContent } {
  return isOperationNode(node) && node.content.type === "textGeneration";
}

export function isActionNode(node: Node): node is OperationNode & { content: ActionContent } {
  return isOperationNode(node) && node.content.type === "action";
}

export function isQueryNode(node: Node): node is OperationNode & { content: QueryContent } {
  return isOperationNode(node) && node.content.type === "query";
}

export function isTextNode(node: Node): node is VariableNode & { content: TextContent } {
  return isVariableNode(node) && node.content.type === "text";
}

export function isFileNode(node: Node): node is VariableNode & { content: FileContent } {
  return isVariableNode(node) && node.content.type === "file";
}


/**
 * Creates a branded ID type with a specific prefix
 */
function createIdSchema(prefix: string) {
  const regex = new RegExp(`^${prefix}_[a-zA-Z0-9]+$`);
  return z.string().refine((val) => regex.test(val), {
    message: `ID must start with "${prefix}_" followed by alphanumeric characters`,
  });
}

/**
 * Generates a unique ID with the given prefix
 */
function generateId(prefix: string): string {
  const randomPart = Math.random().toString(36).substring(2, 15) +
    Math.random().toString(36).substring(2, 15);
  return `${prefix}_${randomPart}`;
}


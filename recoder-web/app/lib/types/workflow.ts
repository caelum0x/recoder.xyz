/**
 * Creates an empty workspace with default settings
 */
export function createEmptyWorkspace(name?: string): Workspace {
  return {
    id: generateWorkspaceId(),
    name,
    schemaVersion: "20250221",
    nodes: [],
    connections: [],
    ui: {
      nodeState: {},
      viewport: { x: 0, y: 0, zoom: 1 },
      currentShortcutScope: "canvas",
      selectedConnectionIds: [],
    },
  };
}

/**
 * Creates a text generation operation node
 */
export function createTextGenerationNode(params: {
  name?: string;
  position: Position;
  prompt?: string;
  provider?: "anthropic" | "google" | "openai" | "perplexity";
  modelId?: string;
}): OperationNode {
  const nodeId = generateNodeId();
  return {
    id: nodeId,
    name: params.name ?? "Text Generation",
    type: "operation",
    inputs: [
      {
        id: generateInputId(),
        label: "Context",
        accessor: "context",
        isRequired: false,
      },
    ],
    outputs: [
      {
        id: generateOutputId(),
        label: "Generated Text",
        accessor: "generated-text",
      },
    ],
    content: {
      type: "textGeneration",
      llm: {
        provider: params.provider ?? "anthropic",
        id: params.modelId ?? "claude-3-5-sonnet-20241022",
      },
      prompt: params.prompt,
    },
  };
}

/**
 * Creates a text variable node
 */
export function createTextNode(params: {
  name?: string;
  position: Position;
  text?: string;
}): VariableNode {
  const nodeId = generateNodeId();
  return {
    id: nodeId,
    name: params.name ?? "Text",
    type: "variable",
    inputs: [],
    outputs: [
      {
        id: generateOutputId(),
        label: "Text",
        accessor: "text",
      },
    ],
    content: {
      type: "text",
      text: params.text ?? "",
    },
  };
}

/**
 * Creates a connection between two nodes
 */
export function createConnection(params: {
  outputNode: NodeReference;
  outputId: OutputId;
  inputNode: NodeReference;
  inputId: InputId;
}): Connection {
  return {
    id: generateConnectionId(),
    ...params,
  };
}

/**
 * Creates a new generation in the created state
 */
export function createGeneration(params: {
  context: GenerationContext;
}): CreatedGeneration {
  return {
    id: generateGenerationId(),
    context: params.context,
    status: "created",
    createdAt: Date.now(),
  };
}


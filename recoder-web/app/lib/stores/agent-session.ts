/**
 * Agent Session Store
 * Manages the state for the autonomous Agent Mode (Composer).
 *
 * Flow: idle -> analyzing -> planning -> executing -> verifying -> fixing -> reviewing -> complete
 *
 * Uses nanostores for lightweight reactive state, consistent with the rest of recoder-web.
 */

import { atom, map } from 'nanostores';
import { createScopedLogger } from '~/utils/logger';

const logger = createScopedLogger('AgentSession');

// ============================================================================
// Phase & Status Types
// ============================================================================

export type AgentPhase =
  | 'idle'
  | 'analyzing'
  | 'planning'
  | 'executing'
  | 'verifying'
  | 'fixing'
  | 'reviewing'
  | 'complete'
  | 'error'
  | 'interrupted';

export interface AgentStep {
  id: string;
  phase: AgentPhase;
  label: string;
  detail?: string;
  status: 'pending' | 'active' | 'complete' | 'error' | 'skipped';
  startedAt?: number;
  completedAt?: number;
  /** Tokens consumed during this step */
  tokensUsed?: number;
}

// ============================================================================
// File Change Types (for agent diff review)
// ============================================================================

export interface AgentFileChange {
  path: string;
  type: 'create' | 'update' | 'delete';
  oldContent?: string;
  newContent?: string;
  /** Whether the user has selected this file for approval */
  selected: boolean;
  /** Summary of what changed (generated by agent) */
  summary?: string;
}

// ============================================================================
// Shell Command Tracking
// ============================================================================

export interface AgentShellCommand {
  id: string;
  command: string;
  output?: string;
  exitCode?: number;
  status: 'pending' | 'running' | 'complete' | 'error';
  startedAt: number;
  completedAt?: number;
}

// ============================================================================
// Plan Types
// ============================================================================

export interface AgentPlanStep {
  id: string;
  description: string;
  type: 'analyze' | 'create' | 'modify' | 'delete' | 'shell' | 'verify';
  targetFile?: string;
  status: 'pending' | 'complete' | 'error';
}

export interface AgentPlan {
  title: string;
  summary: string;
  steps: AgentPlanStep[];
  estimatedFiles: number;
  estimatedCommands: number;
}

// ============================================================================
// Session Types
// ============================================================================

export interface AgentSession {
  /** Unique session ID */
  id: string;
  /** The user's original prompt */
  prompt: string;
  /** Current phase */
  phase: AgentPhase;
  /** Timeline of steps for the UI */
  steps: AgentStep[];
  /** The generated plan (after planning phase) */
  plan: AgentPlan | null;
  /** File changes accumulated during execution */
  fileChanges: AgentFileChange[];
  /** Shell commands executed */
  shellCommands: AgentShellCommand[];
  /** Current fix iteration (max 5) */
  fixIteration: number;
  /** Max fix iterations allowed */
  maxFixIterations: number;
  /** Errors encountered during verification */
  verificationErrors: string[];
  /** Whether the user has interrupted the session */
  interrupted: boolean;
  /** Snapshot ID taken before agent started (for undo) */
  snapshotId: string | null;
  /** Timestamp when the session started */
  startedAt: number;
  /** Timestamp when the session completed */
  completedAt: number | null;
  /** Streaming text being generated (for live display) */
  streamingText: string;
  /** Project ID */
  projectId: string | null;
}

// ============================================================================
// Default State
// ============================================================================

function createDefaultSession(): AgentSession {
  return {
    id: '',
    prompt: '',
    phase: 'idle',
    steps: [],
    plan: null,
    fileChanges: [],
    shellCommands: [],
    fixIteration: 0,
    maxFixIterations: 5,
    verificationErrors: [],
    interrupted: false,
    snapshotId: null,
    startedAt: 0,
    completedAt: null,
    streamingText: '',
    projectId: null,
  };
}

// ============================================================================
// Store Atoms
// ============================================================================

/** The active agent session (map for granular updates) */
export const agentSessionStore = map<AgentSession>(createDefaultSession());

/** Whether an agent session is currently active */
export const agentSessionActive = atom<boolean>(false);

/** AbortController for the current agent session (not stored in nanostores) */
let currentAbortController: AbortController | null = null;

// ============================================================================
// Session Lifecycle
// ============================================================================

/**
 * Start a new agent session
 */
export function startAgentSession(prompt: string, projectId: string | null): string {
  const sessionId = `agent-${Date.now()}-${Math.random().toString(36).slice(2, 9)}`;

  // Create abort controller for this session
  currentAbortController = new AbortController();

  const steps: AgentStep[] = [
    { id: 'analyze', phase: 'analyzing', label: 'Analyzing codebase', status: 'pending' },
    { id: 'plan', phase: 'planning', label: 'Creating plan', status: 'pending' },
    { id: 'execute', phase: 'executing', label: 'Executing changes', status: 'pending' },
    { id: 'verify', phase: 'verifying', label: 'Verifying build', status: 'pending' },
    { id: 'review', phase: 'reviewing', label: 'Ready for review', status: 'pending' },
  ];

  agentSessionStore.set({
    id: sessionId,
    prompt,
    phase: 'analyzing',
    steps,
    plan: null,
    fileChanges: [],
    shellCommands: [],
    fixIteration: 0,
    maxFixIterations: 5,
    verificationErrors: [],
    interrupted: false,
    snapshotId: null,
    startedAt: Date.now(),
    completedAt: null,
    streamingText: '',
    projectId,
  });

  agentSessionActive.set(true);

  logger.info(`[AgentSession] Started session ${sessionId} for: "${prompt.slice(0, 80)}..."`);
  return sessionId;
}

/**
 * Update the current phase and mark timeline steps accordingly
 */
export function setAgentPhase(phase: AgentPhase, detail?: string): void {
  const session = agentSessionStore.get();
  const now = Date.now();

  const steps = session.steps.map((step) => {
    if (step.phase === phase) {
      return { ...step, status: 'active' as const, detail, startedAt: now };
    }

    // Mark previous steps as complete
    if (step.status === 'active') {
      return { ...step, status: 'complete' as const, completedAt: now };
    }

    return step;
  });

  // If entering 'fixing' phase, insert a fix step dynamically
  if (phase === 'fixing') {
    const fixStep: AgentStep = {
      id: `fix-${session.fixIteration + 1}`,
      phase: 'fixing',
      label: `Auto-fixing (attempt ${session.fixIteration + 1}/${session.maxFixIterations})`,
      detail,
      status: 'active',
      startedAt: now,
    };

    // Insert fix step before the verify step
    const verifyIdx = steps.findIndex((s) => s.id === 'verify');
    if (verifyIdx >= 0) {
      steps.splice(verifyIdx, 0, fixStep);
    } else {
      steps.push(fixStep);
    }
  }

  agentSessionStore.setKey('phase', phase);
  agentSessionStore.setKey('steps', steps);

  logger.info(`[AgentSession] Phase -> ${phase}${detail ? `: ${detail}` : ''}`);
}

/**
 * Set the agent plan
 */
export function setAgentPlan(plan: AgentPlan): void {
  agentSessionStore.setKey('plan', plan);
  logger.info(`[AgentSession] Plan set: "${plan.title}" with ${plan.steps.length} steps`);
}

/**
 * Add or update a file change
 */
export function addFileChange(change: Omit<AgentFileChange, 'selected'>): void {
  const session = agentSessionStore.get();
  const existing = session.fileChanges.findIndex((f) => f.path === change.path);
  const fileChange: AgentFileChange = { ...change, selected: true };

  let updated: AgentFileChange[];
  if (existing >= 0) {
    updated = [...session.fileChanges];
    updated[existing] = fileChange;
  } else {
    updated = [...session.fileChanges, fileChange];
  }

  agentSessionStore.setKey('fileChanges', updated);
}

/**
 * Add a shell command execution
 */
export function addShellCommand(cmd: Omit<AgentShellCommand, 'id' | 'status' | 'startedAt'>): string {
  const id = `cmd-${Date.now()}-${Math.random().toString(36).slice(2, 5)}`;
  const session = agentSessionStore.get();

  const shellCmd: AgentShellCommand = {
    id,
    command: cmd.command,
    output: cmd.output,
    exitCode: cmd.exitCode,
    status: 'running',
    startedAt: Date.now(),
  };

  agentSessionStore.setKey('shellCommands', [...session.shellCommands, shellCmd]);
  return id;
}

/**
 * Update a shell command's result
 */
export function updateShellCommand(id: string, update: Partial<AgentShellCommand>): void {
  const session = agentSessionStore.get();
  const commands = session.shellCommands.map((cmd) =>
    cmd.id === id ? { ...cmd, ...update } : cmd,
  );
  agentSessionStore.setKey('shellCommands', commands);
}

/**
 * Set verification errors
 */
export function setVerificationErrors(errors: string[]): void {
  agentSessionStore.setKey('verificationErrors', errors);
}

/**
 * Increment fix iteration
 */
export function incrementFixIteration(): number {
  const session = agentSessionStore.get();
  const next = session.fixIteration + 1;
  agentSessionStore.setKey('fixIteration', next);
  return next;
}

/**
 * Update streaming text (for live display during LLM generation)
 */
export function setStreamingText(text: string): void {
  agentSessionStore.setKey('streamingText', text);
}

/**
 * Toggle file selection for review
 */
export function toggleFileSelection(path: string): void {
  const session = agentSessionStore.get();
  const updated = session.fileChanges.map((f) =>
    f.path === path ? { ...f, selected: !f.selected } : f,
  );
  agentSessionStore.setKey('fileChanges', updated);
}

/**
 * Select or deselect all files
 */
export function selectAllFiles(selected: boolean): void {
  const session = agentSessionStore.get();
  const updated = session.fileChanges.map((f) => ({ ...f, selected }));
  agentSessionStore.setKey('fileChanges', updated);
}

/**
 * Set the snapshot ID (for undo)
 */
export function setSnapshotId(snapshotId: string): void {
  agentSessionStore.setKey('snapshotId', snapshotId);
}

/**
 * Interrupt the current agent session
 */
export function interruptAgentSession(): void {
  if (currentAbortController) {
    currentAbortController.abort();
    currentAbortController = null;
  }

  agentSessionStore.setKey('interrupted', true);
  setAgentPhase('interrupted', 'Session interrupted by user');
  logger.info('[AgentSession] Interrupted by user');
}

/**
 * Get the current AbortSignal (for passing to fetch/LLM calls)
 */
export function getAgentAbortSignal(): AbortSignal | undefined {
  return currentAbortController?.signal;
}

/**
 * Complete the agent session
 */
export function completeAgentSession(): void {
  setAgentPhase('complete');
  agentSessionStore.setKey('completedAt', Date.now());
  currentAbortController = null;
  logger.info('[AgentSession] Session complete');
}

/**
 * Set error state
 */
export function errorAgentSession(error: string): void {
  setAgentPhase('error', error);
  agentSessionStore.setKey('completedAt', Date.now());
  currentAbortController = null;
  logger.error(`[AgentSession] Error: ${error}`);
}

/**
 * Reset / close the agent session
 */
export function resetAgentSession(): void {
  currentAbortController?.abort();
  currentAbortController = null;
  agentSessionStore.set(createDefaultSession());
  agentSessionActive.set(false);
  logger.info('[AgentSession] Session reset');
}

/**
 * Get selected file changes (for approval)
 */
export function getSelectedFileChanges(): AgentFileChange[] {
  return agentSessionStore.get().fileChanges.filter((f) => f.selected);
}

/**
 * Get summary stats for the current session
 */
export function getSessionStats(): {
  filesCreated: number;
  filesModified: number;
  filesDeleted: number;
  commandsRun: number;
  fixIterations: number;
  duration: number;
} {
  const session = agentSessionStore.get();
  const created = session.fileChanges.filter((f) => f.type === 'create').length;
  const modified = session.fileChanges.filter((f) => f.type === 'update').length;
  const deleted = session.fileChanges.filter((f) => f.type === 'delete').length;
  const duration = session.completedAt
    ? session.completedAt - session.startedAt
    : Date.now() - session.startedAt;

  return {
    filesCreated: created,
    filesModified: modified,
    filesDeleted: deleted,
    commandsRun: session.shellCommands.length,
    fixIterations: session.fixIteration,
    duration,
  };
}

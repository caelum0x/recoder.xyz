'use client';

/**
 * Social Feed Component - TikTok-style infinite scroll for AI content
 * KILLER FEATURE: Transform AI development into social discovery experience
 */

import React, { useState, useEffect } from 'react';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { Badge } from '@/components/ui/badge';
import { Separator } from '@/components/ui/separator';
import { 
  Heart, 
  MessageCircle, 
  Share2, 
  Bookmark, 
  TrendingUp, 
  Clock, 
  User, 
  Star, 
  Play, 
  Eye, 
  Code, 
  Sparkles, 
  Bot, 
  Rocket, 
  Zap,
  Users,
  ThumbsUp,
  Repeat,
  ExternalLink,
  GitFork,
  Crown,
  Flame,
  Activity
} from 'lucide-react';

interface SocialPost {
  id: string;
  type: 'model' | 'agent' | 'project' | 'achievement';
  title: string;
  description: string;
  author: {
    name: string;
    avatar: string;
    verified: boolean;
    followers: number;
  };
  content: {
    preview?: string;
    tags: string[];
    stats: {
      likes: number;
      comments: number;
      shares: number;
      views: number;
    };
  };
  metadata: any;
  createdAt: string;
  trending: boolean;
  featured: boolean;
}

interface SocialFeedProps {
  type?: 'home' | 'trending' | 'following' | 'discover';
  showHeader?: boolean;
  maxItems?: number;
}

export default function SocialFeed({ type = 'home', showHeader = true, maxItems = 10 }: SocialFeedProps) {
  const [posts, setPosts] = useState<SocialPost[]>([]);
  const [loading, setLoading] = useState(true);
  const [likedPosts, setLikedPosts] = useState<Set<string>>(new Set());
  const [savedPosts, setSavedPosts] = useState<Set<string>>(new Set());
  const [showComments, setShowComments] = useState<string | null>(null);

  useEffect(() => {
    loadFeed();
  }, [type]);

  const loadFeed = async () => {
    try {
      const response = await fetch('/api/social/feed', {
        headers: {
          'Authorization': `Bearer ${localStorage.getItem('auth_token') || 'development-token'}`,
          'Content-Type': 'application/json'
        }
      });
      
      const data = await response.json();
      if (data.success && data.data?.posts) {
        // Transform backend data to match frontend interface
        const transformedPosts = data.data.posts.map(post => ({
          id: post.id,
          type: 'model', // Default type for now
          title: post.title,
          description: post.content,
          author: {
            name: post.author.name,
            avatar: post.author.avatar || '/avatars/default.jpg',
            verified: post.author.verified || false,
            followers: Math.floor(Math.random() * 10000) // Placeholder
          },
          content: {
            preview: post.content.substring(0, 100) + '...',
            tags: post.metadata?.technologies || ['AI', 'Development'],
            stats: {
              likes: post.stats.likes,
              comments: post.stats.comments,
              shares: post.stats.shares,
              views: Math.floor(Math.random() * 5000) // Placeholder
            }
          },
          metadata: post.metadata || {},
          createdAt: post.createdAt,
          trending: Math.random() > 0.7,
          featured: Math.random() > 0.8
        }));
        setPosts(transformedPosts);
      } else {
        // Fallback to mock data if backend is unavailable
        const mockPosts: SocialPost[] = [
      {
        id: '1',
        type: 'model',
        title: '🔥 Claude Sonnet 4 Crushing It!',
        description: 'Just tested Claude Sonnet 4 on a complex React component - 2.33T tokens of pure genius! 🤯',
        author: { name: 'DevMaster', avatar: '/avatars/1.jpg', verified: true, followers: 15200 },
        content: {
          preview: 'Performance comparison shows 40% better code quality vs previous models',
          tags: ['Claude', 'React', 'Performance'],
          stats: { likes: 342, comments: 67, shares: 89, views: 2400 }
        },
        metadata: { modelName: 'Claude Sonnet 4', provider: 'Anthropic', tokens: '2.33T' },
        createdAt: '2024-01-15T10:30:00Z',
        trending: true,
        featured: true
      },
      {
        id: '2',
        type: 'project',
        title: '🚀 Built a Full-Stack E-commerce in 10 Minutes!',
        description: 'Used Recoder AI to generate a complete Next.js e-commerce platform with Stripe payments. Mind = blown! 💰',
        author: { name: 'StartupGuru', avatar: '/avatars/2.jpg', verified: false, followers: 8900 },
        content: {
          preview: 'Real working payments, user auth, admin dashboard - all generated by AI',
          tags: ['Next.js', 'E-commerce', 'Stripe', 'AI-Generated'],
          stats: { likes: 892, comments: 156, shares: 234, views: 5600 }
        },
        metadata: { projectType: 'E-commerce', techStack: ['Next.js', 'Stripe', 'PostgreSQL'] },
        createdAt: '2024-01-15T08:15:00Z',
        trending: true,
        featured: false
      },
      {
        id: '3',
        type: 'agent',
        title: '🤖 My AI Agent Just Deployed to Production',
        description: 'Created a specialized debugging agent that found 15 critical bugs in our codebase automatically!',
        author: { name: 'CodeNinja', avatar: '/avatars/3.jpg', verified: true, followers: 23400 },
        content: {
          preview: 'Agent analyzed 50k lines of code in 3 minutes, 95% accuracy rate',
          tags: ['AI Agent', 'Debugging', 'Production', 'Automation'],
          stats: { likes: 567, comments: 89, shares: 123, views: 3200 }
        },
        metadata: { agentType: 'Debugging', efficiency: '95%', linesAnalyzed: '50k' },
        createdAt: '2024-01-15T06:45:00Z',
        trending: false,
        featured: true
      },
      {
        id: '4',
        type: 'achievement',
        title: '🏆 Hit 1000 AI Models Tested!',
        description: 'Just reached my milestone of testing 1000 different AI models. Here are the top 10 performers! 📊',
        author: { name: 'AIResearcher', avatar: '/avatars/4.jpg', verified: true, followers: 45600 },
        content: {
          preview: 'Comprehensive analysis of performance, cost, and reliability across providers',
          tags: ['Research', 'Benchmarks', 'Analysis', 'Community'],
          stats: { likes: 1203, comments: 234, shares: 445, views: 8900 }
        },
        metadata: { achievement: '1000 Models Tested', ranking: 'Top 1%' },
        createdAt: '2024-01-15T05:20:00Z',
        trending: true,
        featured: true
      }
        ];
        setPosts(mockPosts.slice(0, maxItems));
      }
    } catch (error) {
      console.error('Failed to load social feed:', error);
      // Use empty array on error
      setPosts([]);
    } finally {
      setLoading(false);
    }
  };

  const handleLike = (postId: string) => {
    setLikedPosts(prev => {
      const newSet = new Set(prev);
      if (newSet.has(postId)) {
        newSet.delete(postId);
      } else {
        newSet.add(postId);
      }
      return newSet;
    });

    // Update post stats
    setPosts(prev => prev.map(post => 
      post.id === postId 
        ? { 
            ...post, 
            content: { 
              ...post.content, 
              stats: { 
                ...post.content.stats, 
                likes: likedPosts.has(postId) 
                  ? post.content.stats.likes - 1 
                  : post.content.stats.likes + 1 
              } 
            } 
          }
        : post
    ));
  };

  const handleSave = (postId: string) => {
    setSavedPosts(prev => {
      const newSet = new Set(prev);
      if (newSet.has(postId)) {
        newSet.delete(postId);
      } else {
        newSet.add(postId);
      }
      return newSet;
    });
  };

  const getTypeIcon = (type: string) => {
    switch (type) {
      case 'model': return <Bot className="h-4 w-4" />;
      case 'agent': return <Sparkles className="h-4 w-4" />;
      case 'project': return <Code className="h-4 w-4" />;
      case 'achievement': return <Crown className="h-4 w-4" />;
      default: return <Activity className="h-4 w-4" />;
    }
  };

  const getTypeColor = (type: string) => {
    switch (type) {
      case 'model': return 'bg-blue-100 text-blue-800';
      case 'agent': return 'bg-purple-100 text-purple-800';
      case 'project': return 'bg-green-100 text-green-800';
      case 'achievement': return 'bg-yellow-100 text-yellow-800';
      default: return 'bg-gray-100 text-gray-800';
    }
  };

  return (
    <div className="w-full max-w-2xl mx-auto">
      {showHeader && (
        <div className="mb-6">
          <h2 className="text-2xl font-bold text-gray-900 mb-2">
            🌟 Community Feed
          </h2>
          <p className="text-gray-600">
            Discover the latest AI models, agents, and projects from the community
          </p>
          
          {/* Feed Navigation */}
          <div className="flex gap-2 mt-4">
            {['home', 'trending', 'following', 'discover'].map((feedType) => (
              <Button
                key={feedType}
                variant={type === feedType ? 'default' : 'outline'}
                size="sm"
                className="capitalize"
              >
                {feedType === 'trending' && <Flame className="h-4 w-4 mr-1" />}
                {feedType === 'following' && <Users className="h-4 w-4 mr-1" />}
                {feedType === 'discover' && <Zap className="h-4 w-4 mr-1" />}
                {feedType}
              </Button>
            ))}
          </div>
        </div>
      )}

      {/* Feed Posts */}
      <div className="space-y-4">
        {loading ? (
          Array.from({ length: 3 }).map((_, i) => (
            <Card key={i} className="animate-pulse">
              <CardContent className="p-6">
                <div className="flex items-center gap-3 mb-4">
                  <div className="h-10 w-10 bg-gray-200 rounded-full"></div>
                  <div>
                    <div className="h-4 bg-gray-200 rounded w-24 mb-1"></div>
                    <div className="h-3 bg-gray-200 rounded w-16"></div>
                  </div>
                </div>
                <div className="h-4 bg-gray-200 rounded mb-2"></div>
                <div className="h-3 bg-gray-200 rounded mb-4"></div>
                <div className="flex gap-4">
                  <div className="h-8 bg-gray-200 rounded w-16"></div>
                  <div className="h-8 bg-gray-200 rounded w-16"></div>
                  <div className="h-8 bg-gray-200 rounded w-16"></div>
                </div>
              </CardContent>
            </Card>
          ))
        ) : (
          posts.map((post) => (
            <Card key={post.id} className="hover:shadow-lg transition-all duration-200 border-l-4 border-l-blue-500">
              <CardContent className="p-6">
                {/* Post Header */}
                <div className="flex items-center justify-between mb-4">
                  <div className="flex items-center gap-3">
                    <div className="h-10 w-10 bg-gradient-to-br from-blue-500 to-purple-500 rounded-full flex items-center justify-center text-white font-semibold">
                      {post.author.name[0]}
                    </div>
                    <div>
                      <div className="flex items-center gap-2">
                        <span className="font-semibold text-gray-900">{post.author.name}</span>
                        {post.author.verified && <Badge variant="secondary" className="text-xs">✓</Badge>}
                        <span className="text-xs text-gray-500">•</span>
                        <span className="text-xs text-gray-500">{post.author.followers.toLocaleString()} followers</span>
                      </div>
                      <div className="flex items-center gap-2 text-xs text-gray-500">
                        <Clock className="h-3 w-3" />
                        {new Date(post.createdAt).toLocaleDateString()}
                        {post.trending && (
                          <>
                            <span>•</span>
                            <Badge variant="destructive" className="text-xs">
                              <TrendingUp className="h-3 w-3 mr-1" />
                              Trending
                            </Badge>
                          </>
                        )}
                        {post.featured && (
                          <>
                            <span>•</span>
                            <Badge variant="secondary" className="text-xs">
                              <Star className="h-3 w-3 mr-1" />
                              Featured
                            </Badge>
                          </>
                        )}
                      </div>
                    </div>
                  </div>

                  <Badge className={getTypeColor(post.type)}>
                    {getTypeIcon(post.type)}
                    <span className="ml-1 capitalize">{post.type}</span>
                  </Badge>
                </div>

                {/* Post Content */}
                <div className="mb-4">
                  <h3 className="text-lg font-semibold text-gray-900 mb-2">{post.title}</h3>
                  <p className="text-gray-700 mb-3">{post.description}</p>
                  {post.content.preview && (
                    <div className="bg-gray-50 rounded-lg p-3 border-l-4 border-l-blue-400">
                      <p className="text-sm text-gray-600">{post.content.preview}</p>
                    </div>
                  )}
                </div>

                {/* Tags */}
                <div className="flex flex-wrap gap-2 mb-4">
                  {post.content.tags.map((tag, index) => (
                    <Badge key={index} variant="outline" className="text-xs cursor-pointer hover:bg-gray-100">
                      #{tag}
                    </Badge>
                  ))}
                </div>

                <Separator className="my-4" />

                {/* Post Actions */}
                <div className="flex items-center justify-between">
                  <div className="flex items-center gap-6">
                    <Button
                      variant="ghost"
                      size="sm"
                      onClick={() => handleLike(post.id)}
                      className={`flex items-center gap-2 ${
                        likedPosts.has(post.id) ? 'text-red-500' : 'text-gray-500'
                      }`}
                    >
                      <Heart className={`h-4 w-4 ${likedPosts.has(post.id) ? 'fill-current' : ''}`} />
                      <span className="text-sm">{post.content.stats.likes}</span>
                    </Button>

                    <Button
                      variant="ghost"
                      size="sm"
                      onClick={() => setShowComments(showComments === post.id ? null : post.id)}
                      className="flex items-center gap-2 text-gray-500"
                    >
                      <MessageCircle className="h-4 w-4" />
                      <span className="text-sm">{post.content.stats.comments}</span>
                    </Button>

                    <Button
                      variant="ghost"
                      size="sm"
                      className="flex items-center gap-2 text-gray-500"
                    >
                      <Share2 className="h-4 w-4" />
                      <span className="text-sm">{post.content.stats.shares}</span>
                    </Button>

                    <div className="flex items-center gap-1 text-xs text-gray-500">
                      <Eye className="h-3 w-3" />
                      <span>{post.content.stats.views.toLocaleString()}</span>
                    </div>
                  </div>

                  <div className="flex items-center gap-2">
                    <Button
                      variant="ghost"
                      size="sm"
                      onClick={() => handleSave(post.id)}
                      className={`${
                        savedPosts.has(post.id) ? 'text-blue-500' : 'text-gray-500'
                      }`}
                    >
                      <Bookmark className={`h-4 w-4 ${savedPosts.has(post.id) ? 'fill-current' : ''}`} />
                    </Button>

                    {post.type === 'project' && (
                      <Button size="sm" variant="outline">
                        <GitFork className="h-4 w-4 mr-1" />
                        Fork
                      </Button>
                    )}

                    {post.type === 'model' && (
                      <Button size="sm" variant="outline">
                        <Play className="h-4 w-4 mr-1" />
                        Try
                      </Button>
                    )}

                    <Button size="sm">
                      <ExternalLink className="h-4 w-4 mr-1" />
                      View
                    </Button>
                  </div>
                </div>

                {/* Comments Section */}
                {showComments === post.id && (
                  <div className="mt-4 pt-4 border-t border-gray-200">
                    <div className="space-y-3">
                      <div className="text-sm">
                        <div className="font-medium text-gray-900">DevExpert</div>
                        <div className="text-gray-600">This is incredible! How did you achieve such performance?</div>
                      </div>
                      <div className="text-sm">
                        <div className="font-medium text-gray-900">AIEnthusiast</div>
                        <div className="text-gray-600">Amazing work! Can't wait to try this myself 🚀</div>
                      </div>
                    </div>
                    <div className="mt-3 flex gap-2">
                      <input 
                        placeholder="Add a comment..." 
                        className="flex-1 px-3 py-2 border border-gray-300 rounded-md text-sm"
                      />
                      <Button size="sm">Post</Button>
                    </div>
                  </div>
                )}
              </CardContent>
            </Card>
          ))
        )}
      </div>

      {/* Load More */}
      {!loading && posts.length >= maxItems && (
        <div className="text-center mt-6">
          <Button variant="outline" onClick={loadFeed}>
            Load More Posts
          </Button>
        </div>
      )}

      {/* Empty State for Limited Users */}
      {type === 'home' && !loading && (
        <Card className="mt-6 bg-gradient-to-r from-yellow-50 to-orange-50 border-yellow-200">
          <CardContent className="p-6 text-center">
            <div className="mb-4">
              <Flame className="h-12 w-12 text-orange-500 mx-auto mb-2" />
              <h3 className="text-lg font-semibold text-gray-900">🔥 Hit Your Usage Limit?</h3>
              <p className="text-gray-600 mt-2">
                No worries! Keep exploring our community feed, discover new models, and engage with amazing projects.
              </p>
            </div>
            <div className="flex flex-wrap justify-center gap-2">
              <Badge variant="secondary" className="cursor-pointer hover:bg-gray-200">Browse Models</Badge>
              <Badge variant="secondary" className="cursor-pointer hover:bg-gray-200">Community Projects</Badge>
              <Badge variant="secondary" className="cursor-pointer hover:bg-gray-200">Free Resources</Badge>
              <Badge variant="secondary" className="cursor-pointer hover:bg-gray-200">Learning Hub</Badge>
            </div>
          </CardContent>
        </Card>
      )}
    </div>
  );
}
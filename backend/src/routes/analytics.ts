/**
 * Analytics API routes for download tracking and metrics
 */

import { Router, Request, Response } from 'express';
import { AnalyticsService } from '../services/analytics';
import { Logger } from '@recoder/shared';

const router = Router();
const analytics = new AnalyticsService();
const logger = new Logger('AnalyticsAPI');

/**
 * Track download event
 * POST /api/analytics/download
 */
router.post('/download', async (req: Request, res: Response) => {
  try {
    const { version, platform, arch, source } = req.body;
    
    if (!version || !platform || !arch || !source) {
      return res.status(400).json({
        error: 'Missing required fields: version, platform, arch, source'
      });
    }

    await analytics.trackDownload(req, version, platform, arch, source);
    
    res.status(200).json({ success: true });
    
  } catch (error) {
    logger.error('Failed to track download:', error);
    res.status(500).json({ error: 'Internal server error' });
  }
});

/**
 * Track update check event
 * POST /api/analytics/update-check
 */
router.post('/update-check', async (req: Request, res: Response) => {
  try {
    const { currentVersion, channel, platform, arch } = req.body;
    
    if (!currentVersion || !channel || !platform || !arch) {
      return res.status(400).json({
        error: 'Missing required fields: currentVersion, channel, platform, arch'
      });
    }

    await analytics.trackUpdateCheck(req, req.body);
    
    res.status(200).json({ success: true });
    
  } catch (error) {
    logger.error('Failed to track update check:', error);
    res.status(500).json({ error: 'Internal server error' });
  }
});

/**
 * Track usage event
 * POST /api/analytics/usage
 */
router.post('/usage', async (req: Request, res: Response) => {
  try {
    const { version, command, platform, arch, sessionId, success } = req.body;
    
    if (!version || !command || !platform || !arch || !sessionId || success === undefined) {
      return res.status(400).json({
        error: 'Missing required fields: version, command, platform, arch, sessionId, success'
      });
    }

    const event = {
      id: '', // Will be generated by analytics service
      timestamp: Date.now(),
      version,
      command,
      subcommand: req.body.subcommand,
      platform,
      arch,
      sessionId,
      duration: req.body.duration,
      success,
      error: req.body.error,
      userId: req.body.userId,
    };

    await analytics.trackUsage(event);
    
    res.status(200).json({ success: true });
    
  } catch (error) {
    logger.error('Failed to track usage:', error);
    res.status(500).json({ error: 'Internal server error' });
  }
});

/**
 * Get analytics metrics
 * GET /api/analytics/metrics?timeRange=month
 */
router.get('/metrics', async (req: Request, res: Response) => {
  try {
    const timeRange = req.query.timeRange as 'day' | 'week' | 'month' | 'year' || 'month';
    
    if (!['day', 'week', 'month', 'year'].includes(timeRange)) {
      return res.status(400).json({
        error: 'Invalid timeRange. Must be one of: day, week, month, year'
      });
    }

    const metrics = await analytics.getMetrics(timeRange);
    
    res.json(metrics);
    
  } catch (error) {
    logger.error('Failed to get metrics:', error);
    res.status(500).json({ error: 'Internal server error' });
  }
});

/**
 * Generate analytics report
 * GET /api/analytics/report?timeRange=month&format=json
 */
router.get('/report', async (req: Request, res: Response) => {
  try {
    const timeRange = req.query.timeRange as 'day' | 'week' | 'month' | 'year' || 'month';
    const format = req.query.format as 'json' | 'text' || 'json';
    
    if (!['day', 'week', 'month', 'year'].includes(timeRange)) {
      return res.status(400).json({
        error: 'Invalid timeRange. Must be one of: day, week, month, year'
      });
    }

    if (format === 'text') {
      const report = await analytics.generateReport(timeRange);
      res.setHeader('Content-Type', 'text/plain');
      res.send(report);
    } else {
      const metrics = await analytics.getMetrics(timeRange);
      res.json({
        generated: new Date().toISOString(),
        timeRange,
        metrics
      });
    }
    
  } catch (error) {
    logger.error('Failed to generate report:', error);
    res.status(500).json({ error: 'Internal server error' });
  }
});

/**
 * Get download statistics for public display
 * GET /api/analytics/public/downloads
 */
router.get('/public/downloads', async (req: Request, res: Response) => {
  try {
    const timeRange = req.query.timeRange as 'day' | 'week' | 'month' | 'year' || 'month';
    const metrics = await analytics.getMetrics(timeRange);
    
    // Return only public-safe metrics
    const publicMetrics = {
      total: metrics.downloads.total,
      byVersion: metrics.downloads.byVersion,
      byPlatform: metrics.downloads.byPlatform,
      bySource: metrics.downloads.bySource,
      trend: metrics.downloads.trend,
      lastUpdated: new Date().toISOString(),
    };
    
    // Cache for 1 hour
    res.setHeader('Cache-Control', 'public, max-age=3600');
    res.json(publicMetrics);
    
  } catch (error) {
    logger.error('Failed to get public download stats:', error);
    res.status(500).json({ error: 'Internal server error' });
  }
});

/**
 * Health check endpoint
 * GET /api/analytics/health
 */
router.get('/health', (req: Request, res: Response) => {
  res.json({
    status: 'ok',
    timestamp: new Date().toISOString(),
    version: process.env.npm_package_version || 'unknown',
  });
});

export default router;
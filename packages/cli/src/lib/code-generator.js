const { logger } = require('../utils/logger');
const fs = require('fs-extra');
const path = require('path');

class CodeGenerator {
  constructor() {
    this.templates = new Map();
    this.generators = new Map();
  }

  async generateFromPlan(plan, options = {}) {
    try {
      logger.info(`Generating code for ${plan.type} project: ${plan.name}`);
      
      const result = {
        files: [],
        integrations: [],
        tests: [],
        structure: {}
      };

      // Generate project structure
      await this.generateProjectStructure(plan, options.outputDir);
      
      // Generate core files
      const coreFiles = await this.generateCoreFiles(plan, options.outputDir);
      result.files.push(...coreFiles);
      
      // Generate integrations if requested
      if (options.includeRealIntegrations) {
        const integrations = await this.generateIntegrations(plan, options.outputDir);
        result.integrations.push(...integrations);
      }
      
      // Generate tests if requested
      if (options.generateTests) {
        const tests = await this.generateTests(plan, options.outputDir);
        result.tests.push(...tests);
      }

      return result;
    } catch (error) {
      throw new Error(`Code generation failed: ${error.message}`);
    }
  }

  async generateProjectStructure(plan, outputDir) {
    const baseDirs = [
      'src',
      'src/components',
      'src/lib',
      'src/utils',
      'src/types',
      'tests',
      'docs'
    ];

    for (const dir of baseDirs) {
      await fs.ensureDir(path.join(outputDir, dir));
    }
  }

  async generateCoreFiles(plan, outputDir) {
    const files = [];
    
    // Generate package.json
    const packageJson = {
      name: plan.name.toLowerCase().replace(/\s+/g, '-'),
      version: '1.0.0',
      description: plan.description || '',
      main: 'src/index.js',
      scripts: {
        dev: 'next dev',
        build: 'next build',
        start: 'next start',
        test: 'jest'
      },
      dependencies: {},
      devDependencies: {}
    };

    await fs.writeJSON(path.join(outputDir, 'package.json'), packageJson, { spaces: 2 });
    files.push({ path: 'package.json', type: 'config' });

    // Generate README.md
    const readme = `# ${plan.name}

${plan.description || 'Generated by CodeCraft'}

## Getting Started

1. Install dependencies:
\`\`\`bash
npm install
\`\`\`

2. Run development server:
\`\`\`bash
npm run dev
\`\`\`

## Features
${plan.requirements?.functional?.map(req => `- ${req}`).join('\n') || '- Core functionality'}

## Architecture
This project follows production-ready architecture patterns.
`;

    await fs.writeFile(path.join(outputDir, 'README.md'), readme);
    files.push({ path: 'README.md', type: 'documentation' });

    return files;
  }

  async generateIntegrations(plan, outputDir) {
    const integrations = [];
    
    for (const integration of plan.integrations || []) {
      try {
        const result = await this.generateIntegration(integration, outputDir);
        integrations.push({
          name: integration.name,
          type: integration.type,
          status: 'generated',
          files: result.files
        });
      } catch (error) {
        integrations.push({
          name: integration.name,
          type: integration.type,
          status: 'failed',
          error: error.message
        });
      }
    }
    
    return integrations;
  }

  async generateIntegration(integration, outputDir) {
    // Mock integration generation
    const integrationFile = path.join(outputDir, 'src/lib', `${integration.name.toLowerCase()}.js`);
    
    const integrationCode = `// ${integration.name} Integration
// Generated by CodeCraft

export class ${integration.name}Client {
  constructor(apiKey) {
    this.apiKey = apiKey;
  }

  async initialize() {
    // Real ${integration.name} integration code would go here
    console.log('${integration.name} initialized');
  }
}

export default ${integration.name}Client;
`;

    await fs.writeFile(integrationFile, integrationCode);
    
    return {
      files: [`src/lib/${integration.name.toLowerCase()}.js`]
    };
  }

  async generateTests(plan, outputDir) {
    const tests = [];
    
    // Generate basic test file
    const testFile = path.join(outputDir, 'tests/basic.test.js');
    const testCode = `// Basic tests for ${plan.name}
// Generated by CodeCraft

describe('${plan.name}', () => {
  test('should initialize correctly', () => {
    expect(true).toBe(true);
  });
});
`;

    await fs.writeFile(testFile, testCode);
    tests.push({ path: 'tests/basic.test.js', type: 'test' });

    return tests;
  }
}

module.exports = { CodeGenerator };
#!/usr/bin/env node

/**
 * Standalone Collaboration Server
 * KILLER FEATURE: Multi-developer + AI agent pair programming
 * Can be run independently for team collaboration
 */

import chalk from 'chalk';
import { Logger } from '../utils/logger';
import { CollaborationService } from '../../../shared/src/collaboration';
import { portManager } from '../utils/port-manager';

let PORT: number;
const REDIS_URL = process.env.REDIS_URL || 'redis://localhost:6379';

async function startCollaborationServer() {
  console.log(chalk.cyan('🚀 RECODER COLLABORATION SERVER'));
  console.log(chalk.gray('Real-time collaborative development with AI agents'));
  console.log(chalk.magenta('🏆 CURSOR KILLER FEATURE - REAL-TIME COLLABORATION!'));
  console.log();

  try {
    // Get available port using port manager
    PORT = await portManager.getPortForService('collaboration-server');
    console.log(chalk.blue(`📡 Port assigned: ${PORT}`));
    const service = new CollaborationService({
      websocketPort: PORT,
      enableRedis: true,
      redisUrl: REDIS_URL
    });

    // Setup event handlers
    service.on('session-created', (data) => {
      console.log(chalk.green(`📝 New session created: ${data.session.name}`));
      console.log(chalk.gray(`   Session ID: ${data.session.id}`));
      console.log(chalk.gray(`   Created by: ${data.creator.name}`));
    });

    service.on('user-joined-session', (data) => {
      console.log(chalk.blue(`👤 ${data.user.name} joined "${data.session.name}"`));
      console.log(chalk.gray(`   Session users: ${data.session.users.size}`));
    });

    service.on('user-left-session', (data) => {
      console.log(chalk.yellow(`👋 ${data.user.name} left "${data.session.name}"`));
      console.log(chalk.gray(`   Session users: ${data.session.users.size}`));
    });

    service.on('ai-request', async (data) => {
      console.log(chalk.cyan(`🤖 AI request in session ${data.sessionId}`));
      console.log(chalk.gray(`   Request: ${data.request.type || 'unknown'}`));
      
      // Mock AI response for now (would integrate with actual AI system)
      const mockSuggestion = {
        id: `ai-${Date.now()}`,
        type: 'code-completion' as const,
        file: data.request.file || 'unknown.ts',
        position: { line: 1, column: 1 },
        suggestion: `// AI suggestion for: ${data.request.prompt}\nconsole.log('This would be real AI-generated code');`,
        explanation: 'This is a mock AI suggestion. In production, this would be generated by our AI models.',
        confidence: 85,
        agentId: 'claude-assistant',
        agentName: 'Claude Assistant'
      };

      // Send response back to session
      data.respond(mockSuggestion);
    });

    service.on('collaborative-generation-request', (data) => {
      console.log(chalk.magenta(`🚀 Collaborative code generation started`));
      console.log(chalk.gray(`   Session: ${data.sessionId}`));
      console.log(chalk.gray(`   Prompt: ${data.prompt.substring(0, 50)}...`));
      console.log(chalk.gray(`   Initiated by: ${data.initiatedBy}`));
    });

    console.log(chalk.green(`✅ Collaboration server running on port ${PORT}`));
    console.log(chalk.gray(`🔗 WebSocket endpoint: ws://localhost:${PORT}/collaboration`));
    console.log(chalk.gray(`💾 Redis persistence: ${REDIS_URL}`));
    console.log();
    console.log(chalk.magenta('🏆 COMPETITIVE ADVANTAGES:'));
    console.log(chalk.white('• Real-time multi-developer collaboration'));
    console.log(chalk.white('• AI agents integrated into sessions'));
    console.log(chalk.white('• Voice chat for pair programming'));
    console.log(chalk.white('• Session persistence and replay'));
    console.log(chalk.white('• Code conflict resolution'));
    console.log();
    console.log(chalk.yellow('Cursor users are stuck coding alone!'));
    console.log(chalk.green('Press Ctrl+C to stop the server'));

    // Handle graceful shutdown
    process.on('SIGINT', async () => {
      console.log(chalk.yellow('\n🛑 Shutting down collaboration server...'));
      try {
        await service.shutdown();
        console.log(chalk.green('✅ Server shut down gracefully'));
        process.exit(0);
      } catch (error) {
        Logger.error('Failed to shutdown gracefully:', error);
        process.exit(1);
      }
    });

    process.on('SIGTERM', async () => {
      console.log(chalk.yellow('\n🛑 Received SIGTERM, shutting down...'));
      await service.shutdown();
      process.exit(0);
    });

    // Keep the process alive
    setInterval(() => {}, 1000);

  } catch (error: any) {
    console.error(chalk.red(`❌ Failed to start collaboration server: ${error.message}`));
    Logger.error('Collaboration server startup failed:', error);
    process.exit(1);
  }
}

// Run if called directly
if (require.main === module) {
  startCollaborationServer().catch(error => {
    Logger.error('Fatal error:', error);
    process.exit(1);
  });
}

export default startCollaborationServer;
#!/usr/bin/env bash
#
# dev-conductor.sh — one-command local-dev harness for the Recoder conductor backend.
#
# What it does (NO manual steps):
#   1. Sets fixed DEV-ONLY env: API_KEY_HASH_SALT, INTERNAL_SERVICE_KEY, STRICT_AUTH=false.
#   2. Mints (or re-uses) a platform sk_ API key with the conductor scopes the
#      desktop cockpit needs, persisting it to data/api-keys.json.
#   3. Boots the backend on :3001 (PORT=3001 tsx src/server.ts).
#   4. Waits until GET /api/conductor/health AUTHENTICATES with the minted key.
#   5. Prints the exact desktop config (CONDUCTOR base url + sk_ key) and writes
#      it to a gitignored .dev/conductor.json the cockpit can read.
#
# The key + salt are DEV-ONLY local values and are never committed (.dev/ and
# data/api-keys.json are gitignored).
#
# Usage:
#   scripts/dev-conductor.sh           # boot + mint + wait + print (foreground)
#   scripts/dev-conductor.sh --mint-only   # just mint the key + write config, no boot
#
# Env overrides:
#   PORT (default 3001), DEV_CONDUCTOR_SALT, DEV_INTERNAL_SERVICE_KEY,
#   HEALTH_TIMEOUT_SECS (default 60), CLEAN=1 (wipe data/api-keys.json first).
set -euo pipefail

# Resolve docker-backend root (this script lives in docker-backend/scripts/).
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BACKEND_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
cd "${BACKEND_DIR}"

# ---- Fixed DEV-ONLY values (stable across restarts so persisted hashes stay valid) ----
PORT="${PORT:-3001}"
export API_KEY_HASH_SALT="${DEV_CONDUCTOR_SALT:-recoder-dev-conductor-salt-local-only}"
export INTERNAL_SERVICE_KEY="${DEV_INTERNAL_SERVICE_KEY:-dev-internal-key}"
export STRICT_AUTH="false"
export NODE_ENV="${NODE_ENV:-development}"
export DEV_CONDUCTOR_USER_ID="${DEV_CONDUCTOR_USER_ID:-dev-conductor-user}"
HEALTH_TIMEOUT_SECS="${HEALTH_TIMEOUT_SECS:-60}"
BASE_URL="http://localhost:${PORT}"
DEV_DIR="${BACKEND_DIR}/.dev"
CONFIG_PATH="${DEV_DIR}/conductor.json"

mkdir -p "${DEV_DIR}"

if [[ "${CLEAN:-0}" == "1" ]]; then
  rm -f "${BACKEND_DIR}/data/api-keys.json"
  echo "[dev-conductor] CLEAN=1 — removed data/api-keys.json"
fi

# ---- 1. Mint (or re-use) the dev conductor API key ----
echo "[dev-conductor] minting dev conductor API key (salt fixed, persists to data/api-keys.json)..."
MINT_JSON="$(npx --no-install tsx scripts/dev-mint-conductor-key.ts 2>/dev/null | tail -n 1)"
if [[ -z "${MINT_JSON}" ]]; then
  echo "[dev-conductor] ERROR: failed to mint dev API key" >&2
  exit 1
fi

# Extract fields without requiring jq.
extract() { node -e "process.stdout.write((JSON.parse(process.argv[1])['$1'] ?? '') + '')" "${MINT_JSON}"; }
SK_KEY="$(extract apiKey)"
KEY_ID="$(extract keyId)"
USER_ID="$(extract userId)"
if [[ -z "${SK_KEY}" ]]; then
  echo "[dev-conductor] ERROR: minted key was empty" >&2
  exit 1
fi
echo "[dev-conductor] minted key id=${KEY_ID} user=${USER_ID} prefix=${SK_KEY%%_*}_${SK_KEY#sk_}" | sed 's/\(sk_[a-z]*_[A-Za-z0-9]\{4\}\).*/\1.../'

# ---- Write the gitignored desktop config (.dev/conductor.json) ----
node -e '
  const fs = require("fs");
  const cfg = {
    baseUrl: process.argv[1],
    conductorBaseUrl: process.argv[1] + "/api/conductor",
    apiKey: process.argv[2],
    apiKeyHeader: "x-api-key",
    keyId: process.argv[3],
    userId: process.argv[4],
    note: "DEV-ONLY. Generated by scripts/dev-conductor.sh. Not committed.",
    generatedAt: new Date().toISOString(),
  };
  fs.writeFileSync(process.argv[5], JSON.stringify(cfg, null, 2) + "\n");
' "${BASE_URL}" "${SK_KEY}" "${KEY_ID}" "${USER_ID}" "${CONFIG_PATH}"
echo "[dev-conductor] wrote desktop config -> ${CONFIG_PATH}"

print_desktop_config() {
  echo ""
  echo "================ DESKTOP / COCKPIT CONFIG ================"
  echo "CONDUCTOR base url : ${BASE_URL}/api/conductor"
  echo "Backend base url   : ${BASE_URL}"
  echo "Auth header        : x-api-key: ${SK_KEY}"
  echo "Config file        : ${CONFIG_PATH}"
  echo "========================================================="
  echo ""
}

if [[ "${1:-}" == "--mint-only" ]]; then
  print_desktop_config
  echo "[dev-conductor] --mint-only: skipping backend boot."
  exit 0
fi

# ---- 3. Boot the backend on :3001 ----
echo "[dev-conductor] booting backend on :${PORT} (PORT=${PORT} tsx src/server.ts)..."
PORT="${PORT}" npx --no-install tsx src/server.ts &
SERVER_PID=$!

cleanup() {
  if kill -0 "${SERVER_PID}" 2>/dev/null; then
    echo "[dev-conductor] stopping backend (pid ${SERVER_PID})..."
    kill "${SERVER_PID}" 2>/dev/null || true
    wait "${SERVER_PID}" 2>/dev/null || true
  fi
}
trap cleanup EXIT INT TERM

# ---- 4. Wait until conductor health authenticates with the minted key ----
echo "[dev-conductor] waiting for ${BASE_URL}/api/conductor/health to authenticate (timeout ${HEALTH_TIMEOUT_SECS}s)..."
DEADLINE=$(( $(date +%s) + HEALTH_TIMEOUT_SECS ))
AUTHED=0
while [[ "$(date +%s)" -lt "${DEADLINE}" ]]; do
  if ! kill -0 "${SERVER_PID}" 2>/dev/null; then
    echo "[dev-conductor] ERROR: backend process exited during startup" >&2
    exit 1
  fi
  CODE="$(curl -s -o /dev/null -w '%{http_code}' -H "x-api-key: ${SK_KEY}" "${BASE_URL}/api/conductor/health" || echo 000)"
  if [[ "${CODE}" == "200" ]]; then
    AUTHED=1
    break
  fi
  sleep 1
done

if [[ "${AUTHED}" != "1" ]]; then
  echo "[dev-conductor] ERROR: conductor health never returned 200 (last code ${CODE:-none})" >&2
  exit 1
fi

echo "[dev-conductor] conductor health authenticated (200)."
echo "[dev-conductor] verifying conductor surfaces the desktop needs..."
for path in /health /runtimes /workspaces; do
  CODE="$(curl -s -o /dev/null -w '%{http_code}' -H "x-api-key: ${SK_KEY}" "${BASE_URL}/api/conductor${path}" || echo 000)"
  echo "  GET /api/conductor${path} -> ${CODE}"
done

print_desktop_config
echo "[dev-conductor] backend running (pid ${SERVER_PID}). Press Ctrl+C to stop."
wait "${SERVER_PID}"
